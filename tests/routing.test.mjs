import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const source = readFileSync(new URL('../js/routing.js', import.meta.url), 'utf8');
const { routeConnection, segmentBlocked, routeGeometry } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const a = { id: 'a', x: 100, y: 150, w: 80, h: 60 };
const b = { id: 'b', x: 400, y: 150, w: 80, h: 60 };
const start = { x: 140, y: 150 }, end = { x: 360, y: 150 };
assert.equal(routeConnection(start, end, [a, b], 'a', 'b').length, 2);
const obstacle = { id: 'o', x: 250, y: 150, w: 80, h: 100 };
const route = routeConnection(start, end, [a, b, obstacle], 'a', 'b');
assert.ok(route.length > 2);
assert.deepEqual(route[0], start);
assert.deepEqual(route.at(-1), end);
const box = { left: 194, right: 306, top: 84, bottom: 216 };
for (let i = 1; i < route.length; i++) assert.equal(segmentBlocked(route[i - 1], route[i], box), false);
const upwards = routeConnection({ x: 100, y: 120 }, { x: 100, y: 50 }, [a, { ...b, x: 100, y: 20 }], 'a', 'b');
assert.equal(upwards.length, 2);
const leftwards = routeConnection(end, start, [a, b], 'b', 'a');
assert.equal(leftwards.length, 2);
const geometry = routeGeometry(route);
assert.ok(!geometry.d.includes('NaN'));
assert.ok(Number.isFinite(geometry.lx) && Number.isFinite(geometry.ly));
const several = routeConnection(start, end, [a, b, obstacle, { id: 'o2', x: 330, y: 230, w: 60, h: 70 }], 'a', 'b');
assert.ok(several.length > 2);
console.log('Routing checks passed.');
